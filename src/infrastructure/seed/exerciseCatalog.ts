import type { BodyArea } from '@/domain/profile/types';
import type { Exercise, ExerciseGuide } from '@/domain/exercise/types';

export interface CatalogEntry {
  exercise: Exercise;
  guide: ExerciseGuide;
}

export { CATALOG_VERSION } from './catalogVersion';

const SHOULDERS: BodyArea[] = ['shoulder_left', 'shoulder_right'];
const KNEES: BodyArea[] = ['knee_left', 'knee_right'];

type Def = Omit<Exercise, 'isCustom' | 'measure'> & {
  measure?: Exercise['measure'];
  steps: string[];
  mistakes: string[];
};

function entry({ steps, mistakes, measure = 'reps', ...exercise }: Def): CatalogEntry {
  return {
    exercise: { ...exercise, measure, isCustom: false },
    guide: { exerciseId: exercise.id, instructions: steps, commonMistakes: mistakes },
  };
}

